const fail=(code,message)=>{throw new ALDXExportError(code,message);};
function asBytes(a){if(a instanceof Uint8Array)return a; if(a instanceof ArrayBuffer)return new Uint8Array(a); if(ArrayBuffer.isView(a))return new Uint8Array(a.buffer,a.byteOffset,a.byteLength);fail('BAD_BYTES','Expected real Uint8Array/ArrayBuffer generated by server');}
export function crc32(data){const b=asBytes(data);let c=0xFFFFFFFF;for(const v of b)c=table[(c^v)&255]^(c>>>8);return (c^0xFFFFFFFF)>>>0;}
export async function sha256(data){const a=new Uint8Array(await crypto.subtle.digest('SHA-256',asBytes(data)));return [...a].map(x=>x.toString(16).padStart(2,'0')).join('');}
function canonJSON(data){return enc.encode(JSON.stringify(data,Object.keys(data).sort())+'\n');}
// ALDX reference serializes all nested objects using sort_keys=True. Do the same.
function stable(obj){if(Array.isArray(obj))return obj.map(stable);if(obj!==null&&typeof obj==='object')return Object.fromEntries(Object.keys(obj).sort().map(k=>[k,stable(obj[k])]));return obj;}
function json(obj){return enc.encode(JSON.stringify(stable(obj))+'\n');}
function validPath(p){
 if(typeof p!=='string'||!p||p!==p.normalize('NFC')||enc.encode(p).length>1024||p.startsWith('/')||p.includes('\\')||p.includes(':')||p.includes('\0')||p.split('/').some(s=>!s||s==='.'||s==='..'||/[. ]$/.test(s))||/[\x00-\x1f\x7f]/.test(p)||p.split('/').some(s=>/^(con|prn|aux|nul|com[1-9]|lpt[1-9])(\.|$)/i.test(s))) fail('BAD_PATH',`Unsafe file path: ${p}`);
 return p;
}
function readU16(b,o){return b[o]|(b[o+1]<<8);}
function readU32(b,o){return (b[o]|(b[o+1]<<8)|(b[o+2]<<16)|(b[o+3]<<24))>>>0;}
function writeU16(view,o,v){view.setUint16(o,v,true);}
function writeU32(view,o,v){view.setUint32(o,v>>>0,true);}
function requireSegment(bytes,pos,len,total=bytes.length){if(pos<0||len<0||pos+len>total)fail('BAD_ZIP','ZIP offset/length outside bounded input');}
function checkUnique(paths){const seen=new Set();for(const p of paths){validPath(p);const s=p.toLowerCase();if(seen.has(s))fail('DUPLICATE_PATH',`Duplicate or case-colliding path: ${p}`);seen.add(s);}for(const p of paths){const a=p.toLowerCase().split('/');for(let i=1;i<a.length;i++)if(seen.has(a.slice(0,i).join('/')))fail('BAD_PATH','File/directory collision');}}
/** Read strict, bounded, ZIP_STORED game packs (current v0.4.1 game export). */
export function extractStoredGameZip(source){
 const b=asBytes(source);if(b.length<22||b.length>ALDX_INPUT_MAX)fail('BAD_INPUT_SIZE','Game ZIP outside allowed size');
 const dv=new DataView(b.buffer,b.byteOffset,b.byteLength);
 let end=-1;for(let i=b.length-22;i>=Math.max(0,b.length-65557);i--){if(readU32(b,i)===0x06054b50&&i+22+readU16(b,i+20)===b.length){end=i;break;}}
 if(end<0)fail('BAD_ZIP','Missing ZIP end record');
 if(readU16(b,end+4)||readU16(b,end+6))fail('BAD_ZIP','Multi-disk ZIP forbidden');
 const n=readU16(b,end+10),size=readU32(b,end+12),start=readU32(b,end+16);
 if(n!==readU16(b,end+8)||n<1||n>128||start+size!==end)fail('BAD_ZIP','Unsupported ZIP central directory');
 let p=start;const result=new Map();let total=0;
 for(let i=0;i<n;i++){
  requireSegment(b,p,46);if(readU32(b,p)!==0x02014b50)fail('BAD_ZIP','Invalid central directory entry');
  const flags=readU16(b,p+8), method=readU16(b,p+10),crc=readU32(b,p+16),packed=readU32(b,p+20),unpacked=readU32(b,p+24);
  const nameLen=readU16(b,p+28),extraLen=readU16(b,p+30),commentLen=readU16(b,p+32),local=readU32(b,p+42),mode=readU32(b,p+38)>>>16;
  requireSegment(b,p+46,nameLen+extraLen+commentLen,end);
  if(flags&1||flags&8)fail('BAD_ZIP','Encrypted or streaming ZIP forbidden');
  if(method!==0||packed!==unpacked)fail('UNSUPPORTED_ZIP','Only stored game ZIP supported; do not silently decompress');
  if((mode&0xF000)===0xA000)fail('BAD_ZIP','Symlinks forbidden');
  const path=validPath(dec.decode(b.subarray(p+46,p+46+nameLen)));
  if(path.endsWith('/')||unpacked>ARCHIVE_FILE_LIMIT)fail('BAD_ZIP','Unexpected entry size/directory');
  requireSegment(b,local,30);if(readU32(b,local)!==0x04034b50)fail('BAD_ZIP','Local ZIP entry mismatch');
  const lname=readU16(b,local+26),lextra=readU16(b,local+28);
  requireSegment(b,local+30,lname+lextra+unpacked,start);
  if(dec.decode(b.subarray(local+30,local+30+lname))!==path||readU16(b,local+8)!==method||readU32(b,local+14)!==crc||readU32(b,local+18)!==packed||readU32(b,local+22)!==unpacked)fail('BAD_ZIP','Local ZIP header does not match central directory');
  const bytes=b.slice(local+30+lname+lextra,local+30+lname+lextra+unpacked);
  if(crc32(bytes)!==crc)fail('BAD_CRC',`CRC mismatch: ${path}`);
  if(result.has(path.toLowerCase()))fail('DUPLICATE_PATH','Case-colliding entry');
  result.set(path,bytes);total+=unpacked;if(total>ALDX_INPUT_MAX)fail('BAD_INPUT_SIZE','Unpacked ZIP exceeds budget');
  p+=46+nameLen+extraLen+commentLen;
 }
 if(p!==end)fail('BAD_ZIP','Trailing central directory bytes');
 checkUnique([...result.keys()]);
 for(const name of REQUIRED_GAME)if(!result.has(name))fail('MISSING_GAME_FILE',`Missing ${name}`);
 if(![...result.keys()].some(k=>k.endsWith('.wav')))fail('MISSING_GAME_WAV','Game ZIP has no WAV');
 try{const m=JSON.parse(dec.decode(result.get('manifest.json')));if(!m||m.schema!=='aldol.sound-mcp-pack/v1'||!Array.isArray(m.assets)||m.assets.length!==1)fail('BAD_GAME_MANIFEST','Expected one generated game sound in a valid manifest');
  for(const asset of m.assets){if(!asset||typeof asset.filename!=='string'||!asset.filename.endsWith('.wav')||!result.has(asset.filename))fail('BAD_GAME_MANIFEST','Manifest sound missing');}
 }catch(e){if(e instanceof ALDXExportError)throw e;fail('BAD_GAME_MANIFEST','Invalid UTF-8/JSON in game manifest');}
 return result;
}
/** Small deterministic ZIP_STORED writer (ZIP64 not needed under 128 KiB inline limit). */
export function zipStored(entries){
 if(!Array.isArray(entries)||entries.length<1||entries.length>1500)fail('BAD_ENTRY_COUNT','Unexpected file count');
 const paths=entries.map(x=>validPath(x[0]));checkUnique(paths);
 const chunks=[],central=[];let cursor=0;
 for(const [name,data] of entries){const body=asBytes(data),fname=enc.encode(name),header=new Uint8Array(30+fname.length);const v=new DataView(header.buffer),crc=crc32(body);
  writeU32(v,0,0x04034b50);writeU16(v,4,20);writeU16(v,6,0x0800);writeU16(v,8,0);writeU16(v,10,0);writeU16(v,12,0);writeU32(v,14,crc);writeU32(v,18,body.length);writeU32(v,22,body.length);writeU16(v,26,fname.length);header.set(fname,30);
  chunks.push(header,body);
  const ch=new Uint8Array(46+fname.length),cv=new DataView(ch.buffer);
  writeU32(cv,0,0x02014b50);writeU16(cv,4,(3<<8)|20);writeU16(cv,6,20);writeU16(cv,8,0x0800);writeU16(cv,10,0);writeU32(cv,16,crc);writeU32(cv,20,body.length);writeU32(cv,24,body.length);writeU16(cv,28,fname.length);writeU32(cv,38,(0o100644<<16)>>>0);writeU32(cv,42,cursor);ch.set(fname,46);central.push(ch);
  cursor+=header.length+body.length;
 }
 const csize=central.reduce((n,a)=>n+a.length,0),tail=new Uint8Array(22),ev=new DataView(tail.buffer);writeU32(ev,0,0x06054b50);writeU16(ev,8,entries.length);writeU16(ev,10,entries.length);writeU32(ev,12,csize);writeU32(ev,16,cursor);
 const output=new Uint8Array(cursor+csize+tail.length);let p=0;for(const c of [...chunks,...central,tail]){output.set(c,p);p+=c.length;}return output;
}
function mediaType(name){const ext=name.slice(name.lastIndexOf('.')).toLowerCase();return MIME[ext]||'application/octet-stream';}
/**
 * Build ALDX v0.2 without ONTEUL from the same bytes of the v0.4.1 game ZIP.
 * @param {{gameZipBytes: Uint8Array|ArrayBuffer, title?: string}} args
 */
export async function makeSoundAldx({gameZipBytes,title='SOUND MCP v0.4.1 Game Demo'}={}){
 const files=extractStoredGameZip(gameZipBytes);
 const packManifest=JSON.parse(dec.decode(files.get('manifest.json')));
 for(const asset of packManifest.assets){
  if(!/^[a-f0-9]{64}$/.test(asset.sha256||'') || asset.byte_length!==files.get(asset.filename).length || await sha256(files.get(asset.filename))!==asset.sha256){
    fail('SOUND_ASSET_HASH_MISMATCH',`Game manifest hash/length mismatch: ${asset.filename}`);
  }
 }
 const sorted=[...files.keys()].sort();
 const hashes=await Promise.all(sorted.map(x=>sha256(files.get(x))));
 const canonical=sorted.map((p,i)=>`${p}\0${hashes[i]}`).join('\n');
 const id='p-'+(await sha256(enc.encode(canonical))).slice(0,20);
 const payload=new Map([...files].map(([p,b])=>['app/'+p,b]));
 const history={version:'0.2.0',events:[{revision:1,operation:'upgrade-v01',path:null}]};
 payload.set('history/events.json',json(history));
 const rows=[];
 for(const [path,data] of [...payload.entries()].sort(([a],[b])=>a.localeCompare(b,'en'))){rows.push({path,size:data.length,sha256:await sha256(data),media_type:mediaType(path)});}
 const manifest={format:'ALDX',schema_version:'0.2.0',project:{id,name:String(title).trim().slice(0,160),revision:1},runtime:{kind:'web',entry:'app/index.html',permissions:[]},files:rows,history:{path:'history/events.json'}};
 if(!manifest.project.name)fail('BAD_TITLE','Project title missing');
 const bytes=zipStored([['manifest.json',json(manifest)],...[...payload].sort(([a],[b])=>a.localeCompare(b,'en'))]);
 return {bytes,manifest,sha256:await sha256(bytes),byte_length:bytes.length,filename:'aldol-sound-game.aldx'};
}
function base64(b){let out='';for(let i=0;i<b.length;i+=24576){let t='';for(const v of b.subarray(i,i+24576))t+=String.fromCharCode(v);out+=btoa(t);}return out;}
/**
 * MCP result for opt-in `format:'aldx'`. Uses the existing v0.4.1 128 KiB direct transport.
 * If output is too large, reject with actionable error instead of returning a mislabeled game ZIP URL.
 */
export async function toAldxMcpResult({gameZipBytes,title}={}){
 const a=await makeSoundAldx({gameZipBytes,title});
 if(a.byte_length>ALDX_INLINE_LIMIT)fail('ALDX_INLINE_TOO_LARGE','ALDX exceeds 128 KiB inline limit; request fewer/shorter sounds or implement authenticated same-site ALDX render route');
 const inline={encoding:'base64',mime_type:'application/octet-stream',filename:a.filename,byte_length:a.byte_length,sha256:a.sha256,data:base64(a.bytes)};
 return {content:[{type:'text',text:JSON.stringify({filename:a.filename,format:'aldx',schema_version:'0.2.0',sha256:a.sha256,byte_length:a.byte_length})},{type:'resource',resource:{uri:`aldol://sound-pack/${a.sha256}.aldx`,mimeType:'application/octet-stream',blob:inline.data}}],structuredContent:{version:'0.4.2',format:'aldx',filename:a.filename,mime_type:inline.mime_type,byte_length:a.byte_length,sha256:a.sha256,aldx_manifest:a.manifest,inline_delivery:inline,persisted:false,download_url:null}};
}
