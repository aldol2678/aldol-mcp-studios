/**
 * SOUND MCP -> ALDX v0.2 deterministic game export (isolated integration module).
 * Accept ONLY already generated game ZIP bytes from sound_export_pack(format:'game').
 * No HTTP fetch, no audio synthesis, no ONTEUL document generation or execution.
 * Runtime: standard ES modules, crypto.subtle, TextEncoder, Uint8Array, btoa.
 */
export const ALDX_EXPORT_VERSION = '0.2.0';
export const ALDX_INLINE_LIMIT = 131072; // exact v0.4.1 inline transport ceiling
export const ALDX_INPUT_MAX = 12 * 1024 * 1024;
const ARCHIVE_FILE_LIMIT = 64 * 1024 * 1024;
const REQUIRED_GAME = ['index.html', 'game-audio.js', 'manifest.json'];
const MIME = {'.html':'text/html','.js':'text/javascript','.json':'application/json','.txt':'text/plain','.wav':'audio/x-wav'};
const enc = new TextEncoder();
const dec = new TextDecoder('utf-8', {fatal:true});
const table = new Uint32Array(256);
for(let n=0;n<256;n++){let c=n;for(let k=0;k<8;k++)c=(c&1)?(0xEDB88320^(c>>>1)):(c>>>1);table[n]=c>>>0;}

